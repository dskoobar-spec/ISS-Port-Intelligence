function makeSheet(
  spec: Omit<
    PierSpecificationSheet,
    | 'brandPrimary'
    | 'brandSecondary'
    | 'motto'
    | 'footerLocation'
    | 'footerOffice'
    | 'footerNoticeTitle'
    | 'footerNoticeBody'
    | 'bannerImageUrl'
  > & { bannerImageUrl?: string }
): PierSpecificationSheet {
  return {
    brandPrimary: 'INCHCAPE',
    brandSecondary: 'SHIPPING SERVICES',
    motto: DEFAULT_MOTTO,
    bannerImageUrl: spec.bannerImageUrl ?? TASP_DEFAULT_BANNER,
    footerLocation: DEFAULT_FOOTER_LOCATION,
    footerOffice: DEFAULT_FOOTER_OFFICE,
    footerNoticeTitle: DEFAULT_NOTICE_TITLE,
    footerNoticeBody: DEFAULT_NOTICE_BODY,
    ...spec,
  };
}

